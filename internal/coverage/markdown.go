// Markdown renders the report as docs/coverage.md: the three measures in
// their own sections, never added together. With the parity baseline and
// the overlay files read, every operation also shows its evidence, each
// switch and overlay evidence item the label its recording gives it, and
// the switches and overlay items a recording settles are listed for
// retirement.
func (r Report) Markdown() []byte {
	var b strings.Builder
	b.WriteString("# Coverage\n\n")
	b.WriteString("<!-- Generated by `just coverage-check`; do not edit by hand. -->\n\n")
	b.WriteString("understudy states three separate measures and never adds them together: protocol compliance " +
		"against the Smithy compliance corpus, operation coverage against the AWS models, and the evidence behind " +
		"behavior the models do not fix (ARCHITECTURE.md 3.4).\n")
	r.writeProtocols(&b)
	r.writeServices(&b)
	r.writeSwitches(&b)
	r.writeOverlays(&b)
	if r.showsEvidence() {
		r.writeRetirement(&b)
	}
	return []byte(b.String())
}

// showsEvidence reports whether the page shows the evidence column: only
// with both the parity baseline and the overlay files, without which an
// operation's claims are incomplete.
func (r Report) showsEvidence() bool {
	_, parity := r.Parity.(ParityRead)
	_, overlays := r.Overlays.(OverlaysRead)
	return parity && overlays
}

func (r Report) writeProtocols(b *strings.Builder) {
	b.WriteString("\n## Protocol compliance\n\n")
	b.WriteString("Server-runnable cases of the Smithy protocol compliance corpus, run against the synthetic services " +
		"by `internal/protocoltest`. Every case goes through the edge, so the counts cover its body caps, framing and " +
		"auth parsing; the cases of the synthetic restJson1 and restXml services are sent with SigV4 credentials " +
		"scoped to the service, which the edge routes them by (ADR 0019). The counts come from the checked-in " +
		"`internal/protocoltest/baseline.json` and `skips.json`, which the corpus test holds every run to.\n\n")
	if len(r.Protocols) == 0 {
		b.WriteString("No baseline is recorded.\n")
		return
	}
	table(b, []string{"Protocol", "Kind", "Cases", "Passed", "Skipped", "Failed", "Known"}, len(r.Protocols), func(i int) []string {
		s := r.Protocols[i]
		return []string{string(s.Protocol), string(s.Kind), num(s.Cases), num(s.Passed), num(len(s.Skipped)), num(s.Failed), num(len(s.KnownFailures))}
	})
	r.writeUngenerated(b)
	r.writeKnownFailures(b)
	r.writeSkipped(b)
}

// writeKnownFailures lists the failed cases skips.json accepts until the
// part of understudy each names can express them.
func (r Report) writeKnownFailures(b *strings.Builder) {
	var failed []string
	for _, s := range r.Protocols {
		for _, f := range s.KnownFailures {
			failed = append(failed, row(string(s.Protocol), string(s.Kind), code(f.ID), f.Reason))
		}
	}
	if len(failed) == 0 {
		return
	}
	b.WriteString("\n### Known failures\n\n")
	b.WriteString("Cases understudy fails because a part it builds on cannot yet express what they assert. " +
		"They count as failed above, and Known counts them apart; each reason names, in parentheses, the package to fix.\n\n")
	b.WriteString(row("Protocol", "Kind", "Case", "Reason"))
	b.WriteString("|---|---|---|---|\n")
	for _, f := range failed {
		b.WriteString(f)
	}
}

// writeUngenerated lists the server-runnable cases the counts leave out,
// so they reconcile with the corpus counts of ARCHITECTURE.md 6.4.
func (r Report) writeUngenerated(b *strings.Builder) {
	if len(r.Ungenerated) == 0 {
		return
	}
	noun := "cases are"
	if len(r.Ungenerated) == 1 {
		noun = "case is"
	}
	fmt.Fprintf(b, "\n%d server-runnable %s not generated, so the counts above leave them out "+
		"(ARCHITECTURE.md 6.4 counts them):\n\n", len(r.Ungenerated), noun)
	table(b, []string{"Protocol", "Kind", "Case", "Reason"}, len(r.Ungenerated), func(i int) []string {
		u := r.Ungenerated[i]
		return []string{string(u.Protocol), string(u.Kind), code(u.ID), u.Reason}
	})
}

func (r Report) writeSkipped(b *strings.Builder) {
	var skipped []string
	for _, s := range r.Protocols {
		for _, c := range s.Skipped {
			category := c.Category
			reason := c.Reason
			if c.Label != "" {
				category += " (" + string(c.Label) + ")"
				reason += " Source: " + c.Source
			}
			skipped = append(skipped, row(string(s.Protocol), string(s.Kind), code(c.ID), category, reason))
		}
	}
	if len(skipped) == 0 {
		return
	}
	b.WriteString("\n### Skipped cases\n\n")
	b.WriteString("corpus-bug: the case's expectation is wrong; client-only: only a client can run it; " +
		"aws-differs: AWS does otherwise, with the evidence label.\n\n")
	b.WriteString(row("Protocol", "Kind", "Case", "Category", "Reason"))
	b.WriteString("|---|---|---|---|---|\n")
	for _, s := range skipped {
		b.WriteString(s)
	}
}

func (r Report) writeServices(b *strings.Builder) {
	b.WriteString("\n## Operations\n\n")
	b.WriteString("Every operation of each service's model, with what its handler states: full, stored-only " +
		"(accepted, stored and echoed, with no runtime effect), partial (implemented with named gaps) or unbound " +
		"(answers 501 NotImplemented). Internal and raw operations are not in the models and are listed apart.\n\n")
	if r.showsEvidence() {
		b.WriteString("Evidence is the weakest claim attributed to the operation, and how many of its claims carry that label. " +
			"A claim is an overlay evidence item whose shape is the operation, its input, its output or one of its errors; " +
			"a fidelity switch whose Ops list the operation; or a recorded step that `internal/parity` replays against it. " +
			"Labels, weakest first: contradicted (<fixture>), when the replay differs from AWS; inferred; sdk-source; aws-doc; " +
			"third-party-recorded; aws-recorded, written aws-recorded (<fixture>) when the replay matches AWS and, for a switch " +
			"or overlay entry it settles, fails once the settled field is changed. unassessed: no claim. " +
			"An unbound operation's only claims are recorded steps replayed against it, since the switches and overlay items " +
			"describe behavior it does not have. Overlay items on a service shape apply to every operation of the service and " +
			"are attributed to none; the Overlay entries table shows their labels.\n\n")
	}
	table(b, []string{"Service", "Operations", "Full", "Stored only", "Partial", "Unbound", "Internal", "Raw"}, len(r.Services), func(i int) []string {
		s := r.Services[i]
		n := counts(s.Operations)
		return []string{string(s.Service), num(len(s.Operations)), num(n[0]), num(n[1]), num(n[2]), num(n[3]), num(len(s.Internal)), num(len(s.Raw))}
	})
	for _, s := range r.Services {
		fmt.Fprintf(b, "\n### %s\n\n", s.Service)
		r.operations(b, s.Service, s.Operations)
		if len(s.Internal) > 0 {
			b.WriteString("\nInternal operations:\n\n")
			r.operations(b, s.Service, s.Internal)
		}
		if len(s.Raw) > 0 {
			b.WriteString("\nRaw operations:\n\n")
			r.operations(b, s.Service, s.Raw)
		}
	}
}

// operations writes the table of ops, operations of service svc, with each
// one's evidence when the page shows it.
func (r Report) operations(b *strings.Builder, svc ref.ServiceID, ops []Operation) {
	if !r.showsEvidence() {
		table(b, []string{"Operation", "Status", "Note"}, len(ops), func(i int) []string {
			return []string{ops[i].Name, StatusName(ops[i].Status), note(ops[i].Status)}
		})
		return
	}
	table(b, []string{"Operation", "Status", "Evidence", "Note"}, len(ops), func(i int) []string {
		return []string{ops[i].Name, StatusName(ops[i].Status), r.OperationEvidence(svc, ops[i].Name).String(), note(ops[i].Status)}
	})
}

func (r Report) writeSwitches(b *strings.Builder) {
	b.WriteString("\n## Evidence\n\n### Fidelity switches\n\n")
	if r.showsEvidence() {
		b.WriteString("Named behavior choice points, labelled by what backs their values, with the research they rest on " +
			"and the parity scenario step that settles them, or why none does. A recorded deviation, where AWS was " +
			"recorded doing otherwise, keeps the label of understudy's own choice and a reason that opens \"AWS " +
			"contradicts it\". The count and order follow the label the code states; the Label column shows the " +
			"recording's verdict where a replayed step settles or contradicts the switch.\n\n")
	} else {
		b.WriteString("Named behavior choice points, labelled by what backs their values, with the research they rest on " +
			"and the record-backlog item that settles them.\n\n")
	}
	if len(r.Switches) == 0 {
		b.WriteString("No wired service declares a switch.\n")
		return
	}
	labels := make([]evidence.Label, len(r.Switches))
	for i, s := range r.Switches {
		labels[i] = s.Label
	}
	b.WriteString(byLabel(len(r.Switches), "switch", "switches", labels))
	table(b, []string{"Switch", "Value", "Label", "Reference", "Settled by"}, len(r.Switches), func(i int) []string {
		s := r.Switches[i]
		if !r.showsEvidence() {
			return []string{code(s.Name), code(s.Value), string(s.Label), s.Ref, s.Record}
		}
		return []string{code(s.Name), code(s.Value), ClaimLabelText(labelOf(r.switchSettlement(s), s.Label)), s.Ref, settledBy(s)}
	})
}

// settledBy is a switch's Settled by cell: the scenario step that settles
// it, why none exists, or else its record-backlog item.
func settledBy(s Switch) string {
	switch st := s.Settles.(type) {
	case fidelity.SettledBy:
		return st.Step.String()
	case fidelity.NoScenario:
		return "none: " + st.Reason
	}
	return s.Record
}

// writeRetirement lists the switches and overlay items a recording settles
// while their code label is below aws-recorded.
func (r Report) writeRetirement(b *strings.Builder) {
	b.WriteString("\n### Settled by recording, pending retirement\n\n")
	b.WriteString("Switches and overlay evidence items whose recorded step matches AWS and fails once the settled field " +
		"is changed, while the code still labels them below aws-recorded. Each is ready to retire its lower label: label it " +
		"aws-recorded, with a test that cites the fixture. A switch stays, so the replay keeps checking it; it goes only " +
		"when its choice point leaves the code (ADR 0003, docs/recording-kit.md 6).\n\n")
	list := r.PendingRetirement()
	if len(list) == 0 {
		b.WriteString("None.\n")
		return
	}
	table(b, []string{"Switch or shape", "Code label", "Fixture", "Field"}, len(list), func(i int) []string {
		var name string
		switch s := list[i].Source.(type) {
		case FromSwitch:
			name = s.Name
		case FromOverlay:
			name = s.Shape
		case FromStep:
			name = s.Scenario + "#" + s.Step
		}
		return []string{code(name), string(list[i].Code), list[i].Fixture, list[i].Field}
	})
}

func (r Report) writeOverlays(b *strings.Builder) {
	b.WriteString("\n### Overlay entries\n\n")
	if r.showsEvidence() {
		b.WriteString("Corrections to the vendored models in `codegen/overlays`, one row per evidence item. The count " +
			"and order, strongest evidence first, follow the label the overlay states; the Label column shows the " +
			"recording's verdict where a replayed step settles or contradicts the item.\n\n")
	} else {
		b.WriteString("Corrections to the vendored models in `codegen/overlays`, one row per evidence item, " +
			"strongest evidence first.\n\n")
	}
	switch o := r.Overlays.(type) {
	case OverlaysNotCarried:
		b.WriteString("This report was built by a running server, which does not carry the overlay files; " +
			"docs/coverage.md in the repository lists them.\n")
	case OverlaysRead:
		entries := slices.Clone(o.Entries)
		SortOverlayEntries(entries)
		labels := make([]evidence.Label, len(entries))
		for i, e := range entries {
			labels[i] = e.Label
		}
		b.WriteString(byLabel(len(entries), "evidence item", "evidence items", labels))
		table(b, []string{"Label", "Overlay", "Shape", "Covers", "Source"}, len(entries), func(i int) []string {
			e := entries[i]
			source := e.Source
			if e.Validated != "" {
				source += " (validated " + e.Validated + ")"
			}
			label := string(e.Label)
			if r.showsEvidence() {
				label = ClaimLabelText(labelOf(r.overlaySettlement(e), e.Label))
			}
			return []string{label, e.File, code(e.Shape), strings.Join(e.Covers, ", "), source}
		})
	}
}

// counts returns how many operations have each status, in Statuses order.
func counts(ops []Operation) [4]int {
	var n [4]int
	for _, op := range ops {
		n[statusRank(op.Status)]++
	}
	return n
}

func note(s Status) string {
	switch s := s.(type) {
	case StoredOnly:
		return s.Note
	case Partial:
		return s.Note
	case Full, Unbound:
		return ""
	}
	return ""
}

// byLabel is a sentence counting items per label, strongest first.
func byLabel(total int, one, many string, labels []evidence.Label) string {
	var parts []string
	for _, l := range evidence.Labels() {
		if n := countOf(labels, l); n > 0 {
			parts = append(parts, fmt.Sprintf("%d %s", n, l))
		}
	}
	noun := many
	if total == 1 {
		noun = one
	}
	return fmt.Sprintf("%d %s: %s.\n\n", total, noun, strings.Join(parts, ", "))
}

func countOf(labels []evidence.Label, l evidence.Label) int {
	n := 0
	for _, x := range labels {
		if x == l {
			n++
		}
	}
	return n
}

// table writes a Markdown table with header and n rows from cells.
func table(b *strings.Builder, header []string, n int, cells func(int) []string) {
	b.WriteString(row(header...))
	b.WriteString("|" + strings.Repeat("---|", len(header)) + "\n")
	for i := range n {
		b.WriteString(row(cells(i)...))
	}
}

// row is one table row; a pipe or line break in a cell is escaped so it
// cannot end the cell or the row.
func row(cells ...string) string {
	escaped := make([]string, len(cells))
	for i, c := range cells {
		escaped[i] = strings.NewReplacer("|", `\|`, "\r\n", " ", "\n", " ").Replace(c)
	}
	return "| " + strings.Join(escaped, " | ") + " |\n"
}

func code(s string) string {
	if s == "" {
		return ""
	}
	return "`" + s + "`"
}

func num(n int) string { return strconv.Itoa(n) }

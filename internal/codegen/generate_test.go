var update = flag.Bool("update", false, "rewrite internal/goldenapi from testdata/golden")

// goldenDir holds the generated golden package: checked in, compiled with
// the module and exercised by its own tests.
const goldenDir = "internal/goldenapi"

// goldenInputs reads the fixture model, overlay and service config, then
// appends extra overlays, which apply after the fixture's own.
func goldenInputs(t *testing.T, extra ...string) codegen.Inputs {
	t.Helper()
	read := func(name string) []byte {
		t.Helper()
		b, err := os.ReadFile("testdata/golden/" + name)
		if err != nil {
			t.Fatal(err)
		}
		return b
	}
	cfg, err := codegen.ParseServiceConfig(bytes.NewReader(read("golden.service.json")), "golden")
	if err != nil {
		t.Fatal(err)
	}
	in := codegen.Inputs{
		Config:   cfg,
		Pin:      "fixture0",
		Model:    codegen.Source{Name: "testdata/golden/golden.json", Content: read("golden.json")},
		Overlays: []codegen.Source{{Name: "testdata/golden/overlay.json", Content: read("overlay.json")}},
	}
	for _, o := range extra {
		in.Overlays = append(in.Overlays, codegen.Source{Name: "extra.json", Content: []byte(o)})
	}
	return in
}

// TestGoldenPackage feeds the fixture through every stage (load, overlay,
// closure, classify, effective traits, regex, roles, IR, emit) and compares
// the files with internal/goldenapi, whose own tests show the code works.
func TestGoldenPackage(t *testing.T) {
	files, err := codegen.Generate(goldenInputs(t))
	if err != nil {
		t.Fatal(err)
	}
	if *update {
		if err := codegen.Write(goldenDir, files); err != nil {
			t.Fatal(err)
		}
		return
	}
	if err := codegen.Check(goldenDir, files); err != nil {
		t.Fatalf("%v\nIf the change is intended, run go test ./internal/codegen -run TestGoldenPackage -update and review the diff.", err)
	}
}

// TestWrittenFilesAreWorldReadable: generated sources are ordinary repo
// files that other users (a Docker build context) read, not 0600 temps.
func TestWrittenFilesAreWorldReadable(t *testing.T) {
	dir := t.TempDir()
	if err := codegen.Write(dir, map[string][]byte{"x_gen.go": []byte("package x\n")}); err != nil {
		t.Fatal(err)
	}
	info, err := os.Stat(dir + "/x_gen.go")
	if err != nil {
		t.Fatal(err)
	}
	if got := info.Mode().Perm(); got != 0o644 {
		t.Fatalf("mode = %v, want -rw-r--r--", got)
	}
}

// TestGenerateIsDeterministic: map iteration never reaches the output, so
// the same inputs give the same bytes every time.
func TestGenerateIsDeterministic(t *testing.T) {
	first, err := codegen.Generate(goldenInputs(t))
	if err != nil {
		t.Fatal(err)
	}
	for range 5 {
		again, err := codegen.Generate(goldenInputs(t))
		if err != nil {
			t.Fatal(err)
		}
		if !maps.EqualFunc(first, again, bytes.Equal) {
			t.Fatal("two runs over the same inputs differ")
		}
	}
}

func TestEveryFileCarriesTheHeader(t *testing.T) {
	files, err := codegen.Generate(goldenInputs(t))
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		"bind_gen.go", "errors_gen.go", "examples_gen_test.go", "ops_gen.go", "redact_gen.go", "schema_gen.go",
		"serde_gen.go", "service_gen.go", "types_gen.go", "validate_gen.go",
	}
	if got := slices.Sorted(maps.Keys(files)); !slices.Equal(got, want) {
		t.Fatalf("files = %v, want %v", got, want)
	}
	var documented []string
	for name, src := range files {
		line, _, _ := bytes.Cut(src, []byte("\n"))
		if want := "// Code generated by understudy-gen from api-models-aws@fixture golden.json; DO NOT EDIT."; string(line) != want {
			t.Errorf("%s line 1 = %q, want %q", name, line, want)
		}
		f, err := parser.ParseFile(token.NewFileSet(), name, src, parser.PackageClauseOnly|parser.ParseComments)
		if err != nil {
			t.Fatal(err)
		}
		if f.Doc != nil {
			documented = append(documented, name)
		}
	}
	// The header is not a package comment (a blank line follows it); the
	// one package comment lives in service_gen.go.
	if !slices.Equal(documented, []string{"service_gen.go"}) {
		t.Errorf("files with a package comment = %v, want [service_gen.go]", documented)
	}
}

// TestWriteRemovesOnlyItsOwnStaleFiles: a file is the generator's to remove
// only when its name and its first line both say so.
func TestWriteRemovesOnlyItsOwnStaleFiles(t *testing.T) {
	dir := t.TempDir()
	header := "// Code generated by understudy-gen from api-models-aws@fixture golden.json; DO NOT EDIT.\n\npackage x\n"
	for name, content := range map[string]string{
		"old_gen.go":           header,
		"fixtures_gen_test.go": "package x\n",
		"hand.go":              "package x\n",
	} {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	files := map[string][]byte{"x_gen.go": []byte(header)}
	var drift *codegen.DriftError
	if err := codegen.Check(dir, files); !errors.As(err, &drift) {
		t.Fatalf("Check = %v, want a *DriftError", err)
	}
	if !slices.Equal(drift.Changed, []string{"x_gen.go"}) || !slices.Equal(drift.Stale, []string{"old_gen.go"}) {
		t.Fatalf("Check changed %v, stale %v; want [x_gen.go], [old_gen.go]", drift.Changed, drift.Stale)
	}
	if err := codegen.Write(dir, files); err != nil {
		t.Fatal(err)
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	got := make([]string, 0, len(entries))
	for _, e := range entries {
		got = append(got, e.Name())
	}
	if want := []string{"fixtures_gen_test.go", "hand.go", "x_gen.go"}; !slices.Equal(got, want) {
		t.Fatalf("after Write dir holds %v, want %v", got, want)
	}
}

// TestCheckReportsUnreadableFiles: a file Check cannot read is a broken
// checkout, not drift, and the cause survives.
func TestCheckReportsUnreadableFiles(t *testing.T) {
	dir := t.TempDir()
	if err := os.Mkdir(filepath.Join(dir, "x_gen.go"), 0o750); err != nil {
		t.Fatal(err)
	}
	err := codegen.Check(dir, map[string][]byte{"x_gen.go": []byte("package x\n")})
	var gerr *codegen.Error
	if !errors.As(err, &gerr) || gerr.Stage != codegen.StageWrite || gerr.Err == nil {
		t.Fatalf("Check = %v, want a write-stage *Error with its cause", err)
	}
}

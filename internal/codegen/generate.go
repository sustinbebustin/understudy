// Source is one input file: its repository-relative name and content.
type Source struct {
	Name    string
	Content []byte
}

// Inputs is everything one service's generation reads; Generate is a pure
// function of it.
type Inputs struct {
	Config ServiceConfig
	// Origin names the pinned upstream of the model in the generated
	// header: api-models-aws@1cfdfb4, smithy-protocol-tests@1.74.0.
	Origin string
	Model  Source
	// Overlays apply in order: overlays/common.json, then the service's own.
	Overlays []Source
	IAM      IAMInput
}

// Generate runs every stage after verify (ARCHITECTURE.md 5.4) and returns
// the package's files by name, each formatted and headed
// "// Code generated by understudy-gen ...; DO NOT EDIT.".
func Generate(in Inputs) (map[string][]byte, error) {
	m, err := Load(bytes.NewReader(in.Model.Content), in.Model.Name)
	if err != nil {
		return nil, err
	}
	for _, o := range in.Overlays {
		ov, err := ParseOverlay(bytes.NewReader(o.Content), o.Name)
		if err != nil {
			return nil, err
		}
		if err := m.Merge(ov); err != nil {
			return nil, err
		}
	}
	iam, err := parseIAMTable(in.IAM)
	if err != nil {
		return nil, err
	}
	ir, err := Build(m, in.Config, iam, Header{Origin: in.Origin, ModelFile: path.Base(in.Model.Name)})
	if err != nil {
		return nil, err
	}
	return Emit(ir)
}

// Header names the generated files' source on their first line.
type Header struct {
	Origin    string // the pinned upstream: api-models-aws@1cfdfb4
	ModelFile string // base name of the model file
}

// Emit renders the IR into the package's files.
func Emit(ir *ServiceIR) (map[string][]byte, error) {
	emitters := map[string]func(*ServiceIR) ([]byte, error){
		"service_gen.go":  emitService,
		"types_gen.go":    emitTypes,
		"schema_gen.go":   emitSchema,
		"serde_gen.go":    emitSerde,
		"validate_gen.go": emitValidate,
		"errors_gen.go":   emitErrors,
		"ops_gen.go":      emitOps,
		"redact_gen.go":   emitRedact,
		"bind_gen.go":     emitBind,
	}
	if hasExamples(ir) {
		emitters["examples_gen_test.go"] = emitExamples
	}
	if len(ir.Routes) > 0 {
		emitters["routes_gen.go"] = emitRoutes
	}
	if ir.Cases != nil {
		emitters["cases_gen.go"] = emitCases
	}
	out := make(map[string][]byte, len(emitters))
	for _, name := range slices.Sorted(maps.Keys(emitters)) {
		src, err := emitters[name](ir)
		if err != nil {
			return nil, err
		}
		out[name] = src
	}
	return out, nil
}

// Repo locates the generator's inputs and outputs under a repository root.
type Repo struct {
	Root string
}

// FindRepo walks up from dir to the directory holding go.mod.
func FindRepo(dir string) (Repo, error) {
	d, err := filepath.Abs(dir)
	if err != nil {
		return Repo{}, err
	}
	for {
		if _, err := os.Stat(filepath.Join(d, "go.mod")); err == nil {
			return Repo{Root: d}, nil
		}
		parent := filepath.Dir(d)
		if parent == d {
			return Repo{}, fmt.Errorf("no go.mod above %s; run the generator inside the understudy module", dir)
		}
		d = parent
	}
}

// Services lists the service ids with a codegen/services file.
func (r Repo) Services() ([]ref.ServiceID, error) {
	entries, err := os.ReadDir(filepath.Join(r.Root, "codegen", "services"))
	if err != nil {
		return nil, err
	}
	var out []ref.ServiceID
	for _, e := range entries {
		if name, ok := strings.CutSuffix(e.Name(), ".json"); ok && !e.IsDir() {
			out = append(out, ref.ServiceID(name))
		}
	}
	return out, nil
}

// Inputs reads the inputs of one service.
func (r Repo) Inputs(id ref.ServiceID) (Inputs, error) {
	cfgPath := filepath.Join(r.Root, "codegen", "services", string(id)+".json")
	raw, err := os.ReadFile(cfgPath)
	if err != nil {
		return Inputs{}, fmt.Errorf("service %q: %w; add codegen/services/%s.json", id, err, id)
	}
	cfg, err := ParseServiceConfig(bytes.NewReader(raw), id)
	if err != nil {
		return Inputs{}, err
	}
	pin, modelPath, err := r.upstream(cfg.Model)
	if err != nil {
		return Inputs{}, err
	}
	in := Inputs{Config: cfg, Origin: "api-models-aws@" + pin[:min(7, len(pin))]}
	if in.Model, err = r.read(path.Join("third_party/api-models-aws", modelPath)); err != nil {
		return Inputs{}, err
	}
	actions, err := r.read("third_party/aws-service-reference/actions.json")
	if err != nil {
		return Inputs{}, err
	}
	in.IAM = ActionsTable{Source: actions}
	for _, name := range []string{"codegen/overlays/common.json", "codegen/overlays/" + string(id) + ".json"} {
		src, err := r.read(name)
		if err != nil {
			return Inputs{}, err
		}
		in.Overlays = append(in.Overlays, src)
	}
	return in, nil
}

// OutputDir is where the package of service cfg is written.
func (r Repo) OutputDir(cfg ServiceConfig) string {
	if _, ok := cfg.Destination.(CorpusPackage); ok {
		return r.corpusOutputDir(cfg.Package)
	}
	return filepath.Join(r.Root, "internal", "api", cfg.Package)
}

func (r Repo) read(name string) (Source, error) {
	content, err := os.ReadFile(filepath.Join(r.Root, filepath.FromSlash(name)))
	if err != nil {
		return Source{}, err
	}
	return Source{Name: name, Content: content}, nil
}

// upstream reads the pin and the model path of dir from UPSTREAM.json.
func (r Repo) upstream(dir string) (commit, modelPath string, err error) {
	src, err := r.read("third_party/api-models-aws/UPSTREAM.json")
	if err != nil {
		return "", "", err
	}
	var m struct {
		Commit string `json:"commit"`
		Files  []struct {
			Dir  string `json:"dir"`
			Path string `json:"path"`
		} `json:"files"`
	}
	if err := json.Unmarshal(src.Content, &m); err != nil {
		return "", "", fmt.Errorf("%s: %w", src.Name, err)
	}
	for _, f := range m.Files {
		if f.Dir == dir {
			return m.Commit, f.Path, nil
		}
	}
	return "", "", fmt.Errorf("%s records no model in directory %q", src.Name, dir)
}

// importPaths are the packages generated code may import: the module
// packages ARCHITECTURE.md 2 allows (smithy and its document package,
// awserr, registry, kernel, ref), gen for the corpus packages, and the
// listed standard library packages.
func importPaths() map[string]string {
	const mod = "github.com/sustinbebustin/understudy/internal/"
	return map[string]string{
		"smithy":   mod + "protocol/smithy",
		"document": mod + "protocol/smithy/document",
		"gen":      mod + "protocoltest/gen",
		"awserr":   mod + "awserr",
		"registry": mod + "registry",
		"kernel":   mod + "kernel",
		"ref":      mod + "ref",
		"big":      "math/big",
		"fmt":      "fmt",
		"io":       "io",
		"maps":     "maps",
		"math":     "math",
		"regexp":   "regexp",
		"slices":   "slices",
		"strconv":  "strconv",
		"strings":  "strings",
		"testing":  "testing",
		"time":     "time",
		"utf8":     "unicode/utf8",
	}
}

// headerPrefix and headerSuffix bracket line 1 of every generated file.
// Write tells generated files from hand-written ones by them.
const (
	headerPrefix = "// Code generated by understudy-gen "
	headerSuffix = "; DO NOT EDIT."
)

// file accumulates one generated Go file.
type file struct {
	ir      *ServiceIR
	name    string
	doc     []string // package comment lines, set on one file per package
	body    bytes.Buffer
	imports map[string]bool
	// exampleBodies records that an example literal used exampleBody, so the
	// examples test file declares it.
	exampleBodies bool
}

func newFile(ir *ServiceIR, name string) *file {
	return &file{ir: ir, name: name, imports: map[string]bool{}}
}

// use records an import by its package name.
func (f *file) use(pkgs ...string) {
	for _, p := range pkgs {
		f.imports[p] = true
	}
}

// p writes one formatted line.
func (f *file) p(layout string, args ...any) {
	fmt.Fprintf(&f.body, layout, args...)
	f.body.WriteByte('\n')
}

// bytes renders the file: the header on line 1, the package comment when
// the file carries it, the package clause, the imports and the body, run
// through go/format.
func (f *file) bytes() ([]byte, error) {
	var out bytes.Buffer
	fmt.Fprintf(&out, "%sfrom %s %s%s\n\n", headerPrefix, f.ir.Origin, f.ir.ModelFile, headerSuffix)
	for _, l := range f.doc {
		fmt.Fprintf(&out, "// %s\n", l)
	}
	fmt.Fprintf(&out, "package %s\n\n", f.ir.Package)
	if err := f.writeImports(&out); err != nil {
		return nil, err
	}
	out.Write(f.body.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		return nil, failf(StageEmit, f.name, "the emitted code does not parse: %v\n%s", err, numbered(out.Bytes()))
	}
	return src, nil
}

// writeImports writes the import block: the standard library, then the
// module's packages.
func (f *file) writeImports(out *bytes.Buffer) error {
	if len(f.imports) == 0 {
		return nil
	}
	var std, module []string
	for n := range f.imports {
		path, ok := importPaths()[n]
		if !ok {
			return failf(StageEmit, f.name, "import %q is not one generated code may use", n)
		}
		if first, _, _ := strings.Cut(path, "/"); strings.Contains(first, ".") {
			module = append(module, path)
		} else {
			std = append(std, path)
		}
	}
	out.WriteString("import (\n")
	for i, group := range [][]string{std, module} {
		if i > 0 && len(std) > 0 && len(module) > 0 {
			out.WriteString("\n")
		}
		for _, path := range slices.Sorted(slices.Values(group)) {
			fmt.Fprintf(out, "\t%q\n", path)
		}
	}
	out.WriteString(")\n\n")
	return nil
}

func numbered(src []byte) string {
	var b bytes.Buffer
	for i, line := range bytes.Split(src, []byte("\n")) {
		fmt.Fprintf(&b, "%5d  %s\n", i+1, line)
	}
	return b.String()
}

func goString(s string) string { return strconv.Quote(s) }

// valueType is the Go type of a value of shape s, without the pointer an
// optional member adds.
func (f *file) valueType(s *ShapeIR) string {
	switch s.Type {
	case smithy.TypeString:
		return "string"
	case smithy.TypeEnum, smithy.TypeIntEnum, smithy.TypeStructure, smithy.TypeUnion:
		return s.GoName
	case smithy.TypeUnit:
		if s.IO != nil {
			return s.GoName
		}
		return "struct{}"
	case smithy.TypeBoolean:
		return "bool"
	case smithy.TypeByte:
		return "int8"
	case smithy.TypeShort:
		return "int16"
	case smithy.TypeInteger:
		return "int32"
	case smithy.TypeLong:
		return "int64"
	case smithy.TypeFloat:
		return "float32"
	case smithy.TypeDouble:
		return "float64"
	case smithy.TypeBigInteger:
		f.use("big")
		return "*big.Int"
	case smithy.TypeBigDecimal:
		f.use("smithy")
		return "smithy.BigDecimal"
	case smithy.TypeTimestamp:
		f.use("time")
		return "time.Time"
	case smithy.TypeBlob:
		return "[]byte"
	case smithy.TypeDocument:
		f.use("document")
		return "document.Value"
	case smithy.TypeList:
		return "[]" + f.elemType(s.Members[0])
	case smithy.TypeMap:
		return "map[" + f.valueType(s.Members[0].Target) + "]" + f.elemType(s.Members[1])
	default:
		return "invalid"
	}
}

// pointerable reports whether an optional member of this shape is a pointer.
func pointerable(s *ShapeIR) bool { return !nilAbsent(s.Type) }

// nilAbsent reports whether the Go type of t has nil for "absent" of its own:
// slices, maps, interfaces and *big.Int.
func nilAbsent(t smithy.ShapeType) bool {
	switch t {
	case smithy.TypeList, smithy.TypeMap, smithy.TypeUnion, smithy.TypeDocument, smithy.TypeBlob, smithy.TypeBigInteger:
		return true
	case smithy.TypeStructure, smithy.TypeString, smithy.TypeEnum, smithy.TypeIntEnum, smithy.TypeBoolean,
		smithy.TypeByte, smithy.TypeShort, smithy.TypeInteger, smithy.TypeLong, smithy.TypeFloat,
		smithy.TypeDouble, smithy.TypeBigDecimal, smithy.TypeTimestamp, smithy.TypeUnit:
		return false
	default:
		return false
	}
}

// elemType is the Go type of a list element or map value; sparse
// collections hold pointers so null differs from zero.
func (f *file) elemType(m *MemberIR) string {
	t := f.valueType(m.Target)
	if m.Owner.Sparse && pointerable(m.Target) {
		return "*" + t
	}
	return t
}

// fieldType is the Go type of a structure member. A stream is a smithy.Body
// in an input structure and a smithy.BodySource in an output one.
func (f *file) fieldType(m *MemberIR) string {
	if m.Streaming {
		f.use("smithy")
		if m.Owner.Role&RoleInput != 0 {
			return "smithy.Body"
		}
		return "smithy.BodySource"
	}
	t := f.valueType(m.Target)
	if !m.Value && pointerable(m.Target) {
		return "*" + t
	}
	return t
}

// sortedShapes returns the shapes ordered by Go name, then id, so every
// emitter walks them in one stable order.
func sortedShapes(ir *ServiceIR) []*ShapeIR {
	return slices.SortedFunc(slices.Values(ir.Shapes), func(a, b *ShapeIR) int {
		return cmp.Or(cmp.Compare(a.GoName, b.GoName), cmp.Compare(a.ID, b.ID))
	})
}

// typeDoc is the doc comment of a generated type.
func typeDoc(s *ShapeIR) string {
	switch {
	case s.IO != nil && s.Unit:
		return fmt.Sprintf("// %s is the empty %s of %s.", s.GoName, ioWord(s), s.IO.Name)
	case s.IO != nil:
		return fmt.Sprintf("// %s is the %s of %s, %s.", s.GoName, ioWord(s), s.IO.Name, s.ID)
	case s.Error != nil:
		return fmt.Sprintf("// %s is the error %s.", s.GoName, s.ID)
	default:
		return fmt.Sprintf("// %s is %s.", s.GoName, s.ID)
	}
}

func ioWord(s *ShapeIR) string {
	if s == s.IO.Input {
		return "input"
	}
	return "output"
}

package ui_test

import (
	"bytes"
	"encoding/json"
	"flag"
	"os"
	"testing"

	"github.com/sustinbebustin/understudy/internal/delivery"
	"github.com/sustinbebustin/understudy/internal/ids"
	"github.com/sustinbebustin/understudy/internal/journal"
	"github.com/sustinbebustin/understudy/internal/ref"
)

var updateLabels = flag.Bool("update-labels", false, "write ui/src/labels.gen.ts from the Go enumerations instead of comparing it")

// labelsFile is the UI's generated label table, from this package's
// directory.
const labelsFile = "../../../ui/src/labels.gen.ts"

// names is the String of each of vs, in order.
func names[T interface{ String() string }](vs []T) []string {
	out := make([]string, len(vs))
	for i, v := range vs {
		out[i] = v.String()
	}
	return out
}

// renderLabels writes the label table: each enumeration a TypeScript const
// array of its wire names in value order.
func renderLabels(t *testing.T) []byte {
	t.Helper()
	var b bytes.Buffer
	b.WriteString("// Code generated by TestLabelTable in internal/server/ui/labels_test.go; DO NOT EDIT.\n")
	b.WriteString("// Regenerate: go test ./internal/server/ui -run TestLabelTable -update-labels\n")
	for _, block := range []struct {
		name   string
		values []string
	}{
		{"journalKinds", names(journal.Kinds())},
		{"vias", names(ref.Vias())},
		{"mechanisms", names(delivery.Mechanisms())},
		{"idKinds", names(ids.Kinds())},
	} {
		if len(block.values) == 0 {
			t.Fatalf("the %s enumeration is empty; the table would name nothing", block.name)
		}
		b.WriteString("\nexport const " + block.name + " = [\n")
		for _, v := range block.values {
			q, err := json.Marshal(v)
			if err != nil {
				t.Fatal(err)
			}
			b.WriteString("  " + string(q) + ",\n")
		}
		b.WriteString("] as const;\n")
	}
	return b.Bytes()
}

// The UI's label table is generated from the journal kinds, ref.Via,
// delivery.Mechanism and ids.Kind, so a value added in Go without a
// regenerated table fails here, and the UI's own test fails until it has a
// label for it.
func TestLabelTable(t *testing.T) {
	want := renderLabels(t)
	if *updateLabels {
		if err := os.WriteFile(labelsFile, want, 0o600); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(labelsFile)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("ui/src/labels.gen.ts differs from the Go enumerations; regenerate it with\n"+
			"  go test ./internal/server/ui -run TestLabelTable -update-labels\n"+
			"(or 'just ui'), then give each new name a label in ui/src/labels.ts\n--- got\n%s\n--- want\n%s", got, want)
	}
}
